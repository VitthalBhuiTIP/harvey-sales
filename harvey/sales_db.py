"""A sales-team view of Harvey's data in MySQL (`harvey sales-db`).

Harvey keeps running on SQLite. This builds a separate MySQL database
(MYSQL_SALES_DATABASE, default `harvey_sales`) shaped for a sales team:

    companies, contacts, company_research, sales_signals,
    ai_analysis, email_drafts, activity_logs

Every column says where it comes from, in its MySQL COMMENT:

    [harvey] collected by Harvey from sources and websites; refreshed every sync
    [ai]     generated by Harvey's AI (or its scoring rules); refreshed every sync
    [team]   the sales team's own fields; a sync never writes them

A sync upserts by Harvey's ids and never deletes, so team edits (lead
status, owner, do-not-contact, notes, review decisions) survive every
re-run, including for rows Harvey has since dropped. Those rows are flagged
``in_harvey = 0`` so nobody mistakes them for current ones.

Nothing here sends email: email_drafts is a copy for review.
"""

