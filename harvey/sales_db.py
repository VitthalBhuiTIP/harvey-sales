def database_name() -> str:
    name = os.getenv("MYSQL_SALES_DATABASE") or "harvey_sales"
    _ident(name)
    return name


def create_table_sql(name, columns, pk, keys) -> str:
    lines = [
        f"  {_ident(col)} {typ} COMMENT '{origin} {comment.replace(chr(39), '')}'"
        for col, typ, origin, comment in columns
    ]
    lines.append(f"  PRIMARY KEY ({_ident(pk)})")
    lines += [f"  {k}" for k in keys]
    return (f"CREATE TABLE IF NOT EXISTS {_ident(name)} (\n" + ",\n".join(lines)
            + "\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci")


def upsert_sql(name, columns) -> tuple[str, list[str]]:
    """INSERT ... ON DUPLICATE KEY UPDATE for the non-team columns only."""
    cols = [c for c, _, origin, _ in columns if origin != T]
    updates = ", ".join(f"{_ident(c)} = VALUES({_ident(c)})" for c in cols if c != "id")
    sql = (f"INSERT INTO {_ident(name)} ({', '.join(_ident(c) for c in cols)}) "
           f"VALUES ({', '.join(['%s'] * len(cols))}) ON DUPLICATE KEY UPDATE {updates}")
    return sql, cols


def relevance(score) -> str:
    score = int(score or 0)
    return "High" if score >= 70 else "Medium" if score >= 40 else "Low"


def render(text: str, contact: dict) -> str:
    """Fill a campaign template's merge variables the way the Sender does."""
    from harvey.agents.sender import Sender
    from harvey.models.prospect import Prospect

    fields = Prospect.model_fields
    prospect = Prospect(**{k: v for k, v in contact.items() if k in fields and v is not None})
    return Sender._render(None, text or "", prospect)


def _rows(conn: sqlite3.Connection, sql: str) -> list[dict]:
    conn.row_factory = sqlite3.Row
    return [dict(r) for r in conn.execute(sql)]


async def build_records(sqlite_path: Path, config, ai_model: str) -> dict[str, list[dict]]:
    """Every sales table's rows, from Harvey's SQLite database."""
    from harvey.models.prospect import COMPANY_INBOX_SOURCE
    from harvey.register import build_register, sqlite_query

    conn = sqlite3.connect(f"file:{sqlite_path.as_posix()}?mode=ro", uri=True)
    try:
        companies = _rows(conn, "SELECT * FROM companies")
        prospects = _rows(conn, "SELECT * FROM prospects")
        observations = _rows(conn, "SELECT * FROM observations")
        codes = {r["code"]: r for r in _rows(conn, "SELECT * FROM signal_codes")}
        campaigns = _rows(conn, "SELECT * FROM campaigns")
        outbox = _rows(conn, "SELECT * FROM outbox")
        actions = _rows(conn, "SELECT * FROM actions")
        have = {r["name"] for r in _rows(conn, "SELECT name FROM sqlite_master WHERE type = 'table'")}
        ai = _rows(conn, "SELECT * FROM ai_analyses") if "ai_analyses" in have else []
        ai_drafts = _rows(conn, "SELECT * FROM ai_drafts") if "ai_drafts" in have else []
    finally:
        conn.close()
    register = {r["id"]: r for r in await build_register(sqlite_query(sqlite_path), config)}
    by_company = {c["id"]: c for c in companies}
    by_prospect = {p["id"]: p for p in prospects}

    out: dict[str, list[dict]] = {t[0]: [] for t in TABLES}
    for c in companies:
        out["companies"].append({
            "id": c["id"], "name": c["name"], "website": c["website"], "domain": c["domain"],
            "industry": c["industry"], "location": c["location"],
            "description": c["description"], "company_size": c["company_size"],
            "phone": c.get("phone"), "source_name": c["source"], "source_url": c["source_url"],
            "discovered_at": c["created_at"], "harvey_updated_at": c["updated_at"],
        })
        obs = [o for o in observations if o["company_id"] == c["id"]]
        latest = {o["signal_code"]: o for o in sorted(obs, key=lambda o: o["observed_at"] or "")}
        out["company_research"].append({
            "id": f"{c['id']}:website", "company_id": c["id"], "research_type": "website",
            "website_url": c["website"], "about": c["description"],
            "tech_stack": c.get("tech_stack_json") or "[]",
            "contact_form_url": (latest.get("CONTACT_FORM_URL") or {}).get("value_text"),
            "hiring_roles": "; ".join(dict.fromkeys(
                o["value_text"] for o in obs if o["signal_code"] == "HIRING_ROLE" and o["value_text"])),
            "site_page_count": (latest.get("SITE_PAGE_COUNT") or {}).get("value_num"),
            "researched_at": c.get("profile_checked_at"),
        })
        reg = register.get(c["id"])
        if reg:
            out["ai_analysis"].append({
                "id": f"company_fit:{c['id']}", "analysis_type": "company_fit",
                "company_id": c["id"], "lead_score": reg["fit"], "relevance": relevance(reg["fit"]),
                "reason": " · ".join(reg["fit_reasons"]), "pipeline_status": reg["status"],
                "recommended_action": reg["why_not_contacted"] or "Review and contact",
                "generated_by": "harvey_rules", "analyzed_at": c["updated_at"],
            })

    for p in prospects:
        company = by_company.get(p["company_id"]) or {}
        inbox = p["source"] == COMPANY_INBOX_SOURCE
        name = f"{p['first_name']} {p['last_name']}".strip() or f"{p['company']} team"
        out["contacts"].append({
            "id": p["id"], "company_id": p["company_id"], "full_name": name,
            "first_name": p["first_name"], "last_name": p["last_name"], "designation": p["title"],
            "department": p["department"], "seniority": p["seniority"], "email": p["email"],
            "email_status": p["email_status"], "is_general_inbox": int(inbox),
            "linkedin_url": p["linkedin_url"], "phone": p["phone"],
            "country": company.get("location"), "harvey_status": p["status"],
            "source_name": p["source"], "source_url": p["source_url"],
            "created_at": p["created_at"], "harvey_updated_at": p["updated_at"],
        })
        out["ai_analysis"].append({
            "id": f"contact_score:{p['id']}", "analysis_type": "contact_score",
            "company_id": p["company_id"], "contact_id": p["id"], "lead_score": p["score"],
            "relevance": relevance(p["score"]),
            "reason": f"{p['title'] or 'general inbox'}; email {p['email_status']}",
            "pipeline_status": p["status"], "personalization": p["personalization_notes"],
            "recommended_action": ("Review the draft" if p["status"] == "queued" else
                                   "Find a verified email first" if p["email_status"] not in ("verified", "risky")
                                   else "Review and contact"),
            "generated_by": "harvey_scout", "analyzed_at": p["updated_at"],
        })

    for o in observations:
        code = codes.get(o["signal_code"]) or {}
        out["sales_signals"].append({
            "id": o["id"], "company_id": o["company_id"], "contact_id": o["prospect_id"] or None,
            "signal_code": o["signal_code"], "signal_type": code.get("label"),
            "category": code.get("category"), "description": code.get("description"),
            "value_text": o["value_text"], "value_num": o["value_num"],
            "confidence": o["confidence"], "source": o["collector"],
            "evidence_url": o["evidence_url"], "detected_at": o["observed_at"],
        })

    staged = {(o["campaign_id"], o["prospect_id"], o["step"]) for o in outbox}
    for o in outbox:
        p = by_prospect.get(o["prospect_id"]) or {}
        out["email_drafts"].append({
            "id": o["id"], "campaign_id": o["campaign_id"], "contact_id": o["prospect_id"],
            "company_id": p.get("company_id"), "to_email": o["to_email"], "step": o["step"],
            "subject": o["subject"], "body": o["body"], "ai_model": ai_model,
            "harvey_status": o["status"], "created_at": o["created_at"],
        })
    for camp in campaigns:
        try:
            steps = json.loads(camp["sequence_json"] or "[]")
            ids = json.loads(camp["prospect_ids_json"] or "[]")
        except json.JSONDecodeError:
            continue
        for pid in ids:
            p = by_prospect.get(pid)
            if not p:
                continue
            for i, s in enumerate(steps, start=1):
                step = int(s.get("step") or i)
                if (camp["id"], pid, step) in staged:
                    continue
                out["email_drafts"].append({
                    "id": f"{camp['id']}:{pid}:{step}", "campaign_id": camp["id"],
                    "campaign_name": camp["name"], "contact_id": pid,
                    "company_id": p["company_id"], "to_email": p["email"], "step": step,
                    "subject": render(s.get("subject"), p), "body": render(s.get("body"), p),
                    "delay_days": s.get("delay_days"), "ai_model": ai_model,
                    "harvey_status": camp["status"], "created_at": camp["created_at"],
                })

    lines = lambda raw: "\n".join(json.loads(raw or "[]"))  # noqa: E731
    for a in ai:
        recommended = json.loads(a["contacts_json"] or "[]")
        out["ai_analysis"].append({
            "id": f"openai:{a['company_id']}", "analysis_type": "openai_lead",
            "company_id": a["company_id"], "lead_score": a["relevance_score"],
            "relevance": a["relevance"], "reason": a["relevance_reason"],
            "recommended_action": a["recommended_action"],
            "business_summary": a["business_summary"],
            "sales_opportunities": lines(a["opportunities_json"]),
            "pain_points": lines(a["pain_points_json"]),
            "recommended_contacts": "\n".join(
                f"{(by_prospect.get(c['contact_id']) or {}).get('email', c['contact_id'])}: {c['reason']}"
                for c in recommended),
            "generated_by": a["model"], "analyzed_at": a["created_at"],
        })
    for d in ai_drafts:
        out["email_drafts"].append({
            "id": f"ai:{d['id']}", "campaign_name": "OpenAI lead analysis",
            "contact_id": d["prospect_id"], "company_id": d["company_id"],
            "to_email": d["to_email"], "step": 1, "subject": d["subject"], "body": d["body"],
            "ai_model": d["model"],
            "harvey_status": "edited" if d["edited"] and d["status"] == "pending_review" else d["status"],
            "created_at": d["created_at"],
        })

    for a in actions:
        out["activity_logs"].append({
            "id": a["id"], "event_type": a["action_type"], "agent": a["agent"],
            "details": a["details_json"], "created_at": a["created_at"],
        })
    return out


def write(settings: MySQLSettings, records: dict[str, list[dict]]) -> dict[str, int]:
    """Create the database and tables if needed, then upsert every record."""
    server = _connect_mysql(settings, database=None)
    try:
        with server.cursor() as cur:
            cur.execute(f"CREATE DATABASE IF NOT EXISTS {_ident(settings.database)} "
                        "CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci")
        server.commit()
    finally:
        server.close()

    db = _connect_mysql(settings, database=settings.database)
    counts = {}
    try:
        with db.cursor() as cur:
            for name, columns, pk, keys in TABLES:
                cur.execute(create_table_sql(name, columns, pk, keys))
                _add_missing_columns(cur, settings.database, name, columns)
        now = _now()
        with db.cursor() as cur:
            for name, columns, _, _ in TABLES:
                sql, cols = upsert_sql(name, columns)
                types = {c: t for c, t, _, _ in columns}
                rows = [
                    tuple(now if c == "synced_at" else 1 if c == "in_harvey"
                          else _value(r.get(c), types[c]) for c in cols)
                    for r in records.get(name, [])
                ]
                if rows:
                    cur.executemany(sql, rows)
                # Rows this sync didn't touch are ones Harvey no longer has
                # (a deleted contact, a pending draft replaced on re-analysis).
                # They stay, with the team's edits, but are flagged.
                cur.execute(f"UPDATE {_ident(name)} SET in_harvey = 0 "
                            f"WHERE in_harvey = 1 AND (synced_at IS NULL OR synced_at < %s)", (now,))
                counts[name] = len(rows)
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()
    return counts


def _add_missing_columns(cur, database: str, name: str, columns) -> None:
    """Columns added to TABLES since the table was created (CREATE TABLE IF
    NOT EXISTS leaves an existing table as it was)."""
    cur.execute("SELECT COLUMN_NAME FROM information_schema.COLUMNS "
                "WHERE TABLE_SCHEMA = %s AND TABLE_NAME = %s", (database, name))
    have = {r[0] for r in cur.fetchall()}
    for col, typ, origin, comment in columns:
        if col not in have:
            cur.execute(f"ALTER TABLE {_ident(name)} ADD COLUMN {_ident(col)} {typ} "
                        f"COMMENT '{origin} {comment.replace(chr(39), '')}'")


def _value(value, mysql_type: str):
    if mysql_type.startswith("DATETIME"):
        return to_mysql_value(value, "DATETIME")
    if isinstance(value, str) and mysql_type.startswith("VARCHAR("):
        size = int(mysql_type[8:mysql_type.index(")")])
        return value[:size]
    return value


def _now():
    """Whole seconds: synced_at is a DATETIME, and the in_harvey sweep
    compares against this exact value."""
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).replace(tzinfo=None, microsecond=0)
